#!/usr/bin/env node

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  getAdapterById,
} from '../dist/hooks/autopilot/adapters/index.js';
import { DEFAULT_PIPELINE_CONFIG } from '../dist/hooks/autopilot/pipeline-types.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const taskToken = '__OMC_NAMED_WORKFLOW_TASK__';
const stages = ['ralplan', 'execution', 'ralph', 'qa'];
const prompts = Object.fromEntries(stages.map((stage) => [
  stage,
  getAdapterById(stage).getPrompt({
    idea: taskToken,
    directory: '.',
    config: DEFAULT_PIPELINE_CONFIG,
  }),
]));

const generated = `// Generated by scripts/build-workflow-stage-prompts.mjs from the canonical TypeScript stage adapters.\n// Do not edit this file directly.\n\nconst TASK_TOKEN = ${JSON.stringify(taskToken)};\nconst PROMPTS = Object.freeze(${JSON.stringify(prompts, null, 2)});\n\nexport function resolveCanonicalWorkflowStagePrompt(stageId, task) {\n  const prompt = PROMPTS[stageId];\n  if (typeof prompt !== 'string' || typeof task !== 'string' || task.trim().length === 0) return null;\n  return prompt.split(TASK_TOKEN).join(task.trim());\n}\n`;

for (const relativePath of [
  'scripts/lib/workflow-stage-prompts.mjs',
  'templates/hooks/lib/workflow-stage-prompts.mjs',
]) {
  writeFileSync(join(root, relativePath), generated);
}
